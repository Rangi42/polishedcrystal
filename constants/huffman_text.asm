; Pair indices occupy the token IDs below the space character. Literals from
; the low end of the charmap are shifted above the directly encodable range.
DEF HUFFMAN_FIRST_SHIFTED_CHAR EQU NGRAMS_START
DEF HUFFMAN_LAST_SHIFTED_CHAR  EQU '<ENEMY>'
DEF HUFFMAN_FIRST_SHIFTED_TOKEN EQU '…' + 1
DEF HUFFMAN_TOKEN_SHIFT EQU HUFFMAN_FIRST_SHIFTED_TOKEN - HUFFMAN_FIRST_SHIFTED_CHAR
DEF HUFFMAN_LAST_SHIFTED_TOKEN EQU HUFFMAN_LAST_SHIFTED_CHAR + HUFFMAN_TOKEN_SHIFT
DEF HUFFMAN_ESCAPE EQU $ff
assert HUFFMAN_LAST_SHIFTED_TOKEN < HUFFMAN_ESCAPE
